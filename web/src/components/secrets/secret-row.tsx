import { Eye, EyeOff, History, Lock, MessageSquare, MoreHorizontal, Pencil, RefreshCw, Sparkles, Trash2 } from "lucide-react";
import { useRef } from "react";
import type { Secret } from "@/api/types";
import { CopyButton } from "@/components/copy-button";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuSeparator,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu";
import { Skeleton } from "@/components/ui/skeleton";
import { Tooltip, TooltipContent, TooltipTrigger } from "@/components/ui/tooltip";
import { formatDateTime, formatRelative } from "@/lib/format";
import { daysUntil } from "@/lib/generation";
import { cn } from "@/lib/utils";

export interface SecretRowAbilities {
  edit: boolean;
  remove: boolean;
  history: boolean;
}

/** Small markers for values sekret generated and values it will rotate. */
function GenerationBadges({ secret }: { secret: Secret }) {
  const next = secret.next_rotation_at;
  return (
    <>
      {secret.generated && !next && (
        <Badge variant="outline" className="h-5 gap-1 text-[0.7rem] text-muted-foreground" data-testid="secret-generated-badge">
          <Sparkles className="size-3" />
          Generated
        </Badge>
      )}
      {next != null && (
        <Tooltip>
          <TooltipTrigger asChild>
            <Badge variant="outline" className="h-5 gap-1 border-primary/40 text-[0.7rem] text-primary" data-testid="secret-rotation-badge">
              <RefreshCw className="size-3" />
              {daysUntil(next) === 0 ? "Rotates today" : `Rotates in ${daysUntil(next)}d`}
            </Badge>
          </TooltipTrigger>
          <TooltipContent>Generated by sekret; next rotation {formatDateTime(next)}</TooltipContent>
        </Tooltip>
      )}
    </>
  );
}

interface SecretRowProps {
  secret: Secret;
  revealed: boolean;
  /** Undefined while the value is still loading. */
  value: string | null | undefined;
  abilities: SecretRowAbilities;
  onToggleReveal: () => void;
  onCopyValue: () => Promise<string | null | undefined>;
  onEdit: () => void;
  onDelete: () => void;
  /** `returnTo` is what should get focus back once the drawer or dialog closes. */
  onHistory: (returnTo: HTMLElement | null) => void;
  onRotate: (returnTo: HTMLElement | null) => void;
}

const MASK = "•".repeat(12);

/**
 * Column widths shared with the table header, so "Value" lines up with the values. The last
 * column holds the actions button, plus the version and age on large screens.
 */
export const SECRET_ROW_COLUMNS = "md:grid-cols-[minmax(0,2fr)_minmax(0,3fr)_1.75rem] lg:grid-cols-[minmax(0,2fr)_minmax(0,3fr)_9.25rem]";

export function SecretRow({
  secret,
  revealed,
  value,
  abilities,
  onToggleReveal,
  onCopyValue,
  onEdit,
  onDelete,
  onHistory,
  onRotate,
}: SecretRowProps) {
  const hidden = secret.value_hidden;
  const actions = useRef<HTMLButtonElement>(null);

  return (
    <div
      role="row"
      className={cn(
        "group grid grid-cols-[minmax(0,1fr)_auto] gap-x-2 gap-y-2 border-b px-4 py-3 last:border-b-0 md:items-center",
        SECRET_ROW_COLUMNS,
      )}
      data-testid={`secret-row-${secret.key}`}
    >
      <div role="cell" className="min-w-0">
        <button
          type="button"
          onClick={(event) => onHistory(event.currentTarget)}
          className="-my-1.5 block max-w-full truncate py-1.5 text-left font-mono text-sm font-medium hover:text-primary"
          data-testid="secret-key"
        >
          {secret.key}
        </button>
        <div className="mt-1 flex flex-wrap items-center gap-1.5">
          <GenerationBadges secret={secret} />
          {secret.comment && (
            <Tooltip>
              <TooltipTrigger asChild>
                <span className="flex max-w-full items-center gap-1 truncate text-xs text-muted-foreground" data-testid="secret-comment">
                  <MessageSquare className="size-3 shrink-0" />
                  <span className="truncate first-letter:uppercase">{secret.comment}</span>
                </span>
              </TooltipTrigger>
              <TooltipContent>{secret.comment}</TooltipContent>
            </Tooltip>
          )}
          {secret.tags.map((tag) => (
            <Badge key={tag} variant="secondary" className="h-5 text-[0.7rem]" data-testid={`secret-tag-${tag}`}>
              {tag}
            </Badge>
          ))}
          {/* The Updated column only fits on wide screens. */}
          <span className="text-xs text-muted-foreground tabular-nums lg:hidden" title={secret.updated_by} data-testid="secret-updated-meta">
            v{secret.version} · {formatRelative(secret.updated_at)}
          </span>
        </div>
      </div>

      <div role="cell" className="col-span-2 row-start-2 flex min-w-0 items-center gap-1 md:col-span-1 md:row-start-auto">
        <div
          className="min-w-0 flex-1 rounded-md bg-muted/60 px-2.5 py-1.5 font-mono text-sm"
          data-testid="secret-value"
        >
          {hidden ? (
            <span className="flex items-center gap-1.5 text-muted-foreground" data-testid="secret-no-access">
              <Lock className="size-3.5" />
              No access to value
            </span>
          ) : revealed ? (
            value === undefined ? (
              <Skeleton className="h-4 w-32" />
            ) : (
              <span className="block truncate whitespace-pre" title={value ?? ""}>
                {value || <span className="text-muted-foreground italic">empty</span>}
              </span>
            )
          ) : (
            <span className="text-muted-foreground select-none">{MASK}</span>
          )}
        </div>
        <Button
          variant="ghost"
          size="icon-sm"
          onClick={onToggleReveal}
          disabled={hidden}
          aria-label={revealed ? `Hide ${secret.key}` : `Reveal ${secret.key}`}
          data-testid="secret-reveal"
          className="text-muted-foreground"
        >
          {revealed ? <EyeOff /> : <Eye />}
        </Button>
        <CopyButton value={onCopyValue} label={`Copy ${secret.key}`} disabled={hidden} testId="secret-copy" sensitive />
      </div>

      <div role="cell" className="col-start-2 row-start-1 flex items-start justify-end md:col-start-auto md:row-start-auto md:items-center">
        <span
          className="mr-2 hidden w-28 truncate text-right text-xs whitespace-nowrap text-muted-foreground tabular-nums lg:inline"
          title={secret.updated_by}
        >
          v{secret.version} · {formatRelative(secret.updated_at)}
        </span>
        <DropdownMenu>
          <DropdownMenuTrigger asChild>
            <Button ref={actions} variant="ghost" size="icon-sm" aria-label={`Actions for ${secret.key}`} data-testid="secret-actions">
              <MoreHorizontal />
            </Button>
          </DropdownMenuTrigger>
          <DropdownMenuContent align="end" className="min-w-48">
            {abilities.edit && (
              <DropdownMenuItem onSelect={onEdit} data-testid="secret-edit">
                <Pencil />
                Edit
              </DropdownMenuItem>
            )}
            {/* Typed values can still be rotated from the drawer, behind a warning. */}
            {abilities.edit && (secret.generated || secret.next_rotation_at != null) && (
              <DropdownMenuItem onSelect={() => onRotate(actions.current)} data-testid="secret-rotate">
                <RefreshCw />
                Rotate now
              </DropdownMenuItem>
            )}
            {abilities.history && (
              <DropdownMenuItem onSelect={() => onHistory(actions.current)} data-testid="secret-history">
                <History />
                History and rotation
              </DropdownMenuItem>
            )}
            {abilities.remove && (
              <>
                <DropdownMenuSeparator />
                <DropdownMenuItem variant="destructive" onSelect={onDelete} data-testid="secret-delete">
                  <Trash2 />
                  Delete
                </DropdownMenuItem>
              </>
            )}
            {!abilities.edit && !abilities.history && !abilities.remove && (
              <DropdownMenuItem disabled>No actions available</DropdownMenuItem>
            )}
          </DropdownMenuContent>
        </DropdownMenu>
      </div>
    </div>
  );
}
