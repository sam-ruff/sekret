import { useQuery } from "@tanstack/react-query";
import { CalendarClock, Info, RefreshCw, Sparkles } from "lucide-react";
import { useState } from "react";
import { api } from "@/api/endpoints";
import type { SecretPolicyView } from "@/api/types";
import { ErrorState, ListSkeleton } from "@/components/states";
import { Alert, AlertDescription } from "@/components/ui/alert";
import { Button } from "@/components/ui/button";
import { Spinner } from "@/components/ui/spinner";
import { ToggleGroup, ToggleGroupItem } from "@/components/ui/toggle-group";
import { keys, useApiMutation } from "@/hooks/queries";
import { formatDateTime } from "@/lib/format";
import {
  daysUntil,
  describeEffectiveGenerator,
  describeRotation,
  draftFromPolicy,
  draftProblem,
  overrideFromDraft,
  type PolicyDraft,
} from "@/lib/generation";
import { GeneratorFields, RotationField } from "./generator-fields";

interface Location {
  project: string;
  env: string;
  path: string;
}

interface PolicySectionProps {
  at: Location;
  secretKey: string;
  canEdit: boolean;
  onRotate: () => void;
}

export function PolicySection({ at, secretKey, canEdit, onRotate }: PolicySectionProps) {
  const view = useQuery({
    queryKey: keys.secretPolicy(at.project, at.env, at.path, secretKey),
    queryFn: () => api.secretPolicy(at, secretKey),
  });

  return (
    <section className="space-y-3" data-testid="policy-section">
      <h3 className="text-sm font-semibold">Generation and rotation</h3>
      {view.isPending && <ListSkeleton rows={2} />}
      {view.error && <ErrorState error={view.error} onRetry={() => void view.refetch()} />}
      {view.data && (
        <PolicyForm key={JSON.stringify(view.data.setting)} at={at} secretKey={secretKey} view={view.data} canEdit={canEdit} onRotate={onRotate} />
      )}
    </section>
  );
}

function PolicyForm({ at, secretKey, view, canEdit, onRotate }: PolicySectionProps & { view: SecretPolicyView }) {
  const initialCustom = view.setting.mode === "custom";
  const initialDraft = draftFromPolicy(view.setting.mode === "custom" ? view.setting : view.effective);
  const [custom, setCustom] = useState(initialCustom);
  const [draft, setDraft] = useState<PolicyDraft>(initialDraft);

  const save = useApiMutation({
    mutationFn: () => api.putSecretPolicy(at, secretKey, overrideFromDraft(custom, draft)),
    invalidate: [keys.secretPolicy(at.project, at.env, at.path, secretKey), ["project", at.project, "secrets"]],
    success: `Saved the policy for ${secretKey}`,
  });

  const problem = custom ? draftProblem(draft) : undefined;
  const changed = custom !== initialCustom || (custom && JSON.stringify(draft) !== JSON.stringify(initialDraft));
  const { effective, generated, next_rotation_at: next } = view;

  return (
    <div className="space-y-4 rounded-lg border bg-card p-3">
      <dl className="grid gap-2 text-sm" data-testid="policy-effective">
        <div className="flex items-start gap-2">
          <Sparkles className="mt-0.5 size-4 shrink-0 text-muted-foreground" />
          <div className="min-w-0">
            <dt className="sr-only">Generator</dt>
            <dd data-testid="policy-effective-generator">{describeEffectiveGenerator(effective.generator)}</dd>
          </div>
        </div>
        <div className="flex items-start gap-2">
          <RefreshCw className="mt-0.5 size-4 shrink-0 text-muted-foreground" />
          <div className="min-w-0">
            <dt className="sr-only">Rotation</dt>
            <dd data-testid="policy-effective-rotation">{describeRotation(effective.rotation_days)}</dd>
          </div>
        </div>
        <div className="flex items-start gap-2">
          <CalendarClock className="mt-0.5 size-4 shrink-0 text-muted-foreground" />
          <div className="min-w-0">
            <dt className="sr-only">Next rotation</dt>
            <dd data-testid="policy-next-rotation">
              {next != null
                ? `Next rotation ${formatDateTime(next)} (${daysUntil(next) === 0 ? "today" : `in ${daysUntil(next)} days`})`
                : generated
                  ? "The current value was generated by sekret"
                  : "The current value was typed or imported"}
            </dd>
          </div>
        </div>
      </dl>

      {effective.rotation_days && !generated && (
        <Alert data-testid="policy-not-generated">
          <Info />
          <AlertDescription>
            Rotation applies once a value is generated. sekret never replaces a value it did not create, so use Rotate now to
            start the schedule.
          </AlertDescription>
        </Alert>
      )}

      <ToggleGroup
        type="single"
        variant="outline"
        size="sm"
        value={custom ? "custom" : "inherit"}
        onValueChange={(v) => v && setCustom(v === "custom")}
        disabled={!canEdit}
        className="w-full"
        data-testid="policy-mode"
      >
        <ToggleGroupItem value="inherit" className="flex-1" data-testid="policy-mode-inherit">
          Project default
        </ToggleGroupItem>
        <ToggleGroupItem value="custom" className="flex-1" data-testid="policy-mode-custom">
          Custom
        </ToggleGroupItem>
      </ToggleGroup>

      {custom ? (
        <div className="space-y-4">
          <GeneratorFields
            idPrefix="policy"
            length={draft.length}
            charset={draft.charset}
            disabled={!canEdit}
            onChange={(g) => setDraft({ ...draft, ...g })}
          />
          <RotationField
            idPrefix="policy"
            rotate={draft.rotate}
            days={draft.days}
            disabled={!canEdit}
            onChange={(r) => setDraft({ ...draft, ...r })}
          />
        </div>
      ) : (
        <p className="text-sm text-muted-foreground">
          Follows the project&apos;s secret defaults, set in project settings.
        </p>
      )}

      {canEdit && (
        <div className="flex flex-wrap justify-end gap-2">
          <Button variant="outline" size="sm" onClick={onRotate} data-testid="policy-rotate-now">
            <RefreshCw />
            Rotate now
          </Button>
          <Button size="sm" disabled={!changed || !!problem || save.isPending} onClick={() => save.mutate()} data-testid="policy-save">
            {save.isPending && <Spinner />}
            Save policy
          </Button>
        </div>
      )}
    </div>
  );
}
